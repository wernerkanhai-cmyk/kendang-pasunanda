export const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('kendangLanguage') || 'en');

  const setLang = useCallback((code) => {
    setLanguage(code);
    localStorage.setItem('kendangLanguage', code);
  }, []);

  const t = useCallback((key) => {
    const val = T[language]?.[key] ?? T.en[key];
    return val ?? key;
  }, [language]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage: setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useT() {
  const ctx = useContext(LanguageContext);
  if (!ctx) return (key) => T.en[key] ?? key;
  return ctx.t;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
